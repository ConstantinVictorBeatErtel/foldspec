"""Export Pydantic JSON Schemas and matching frontend TypeScript types."""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from services.api.models import (
    BuildResult,
    DesignProposal,
    DisplayUnits,
    DraftSpec,
    Finding,
    InspectionFeature,
    PartSpec,
    Project,
    TemplateId,
)


CONTRACTS = ROOT / "contracts"
GENERATED = ROOT / "apps" / "web" / "src" / "generated" / "contracts.ts"
MODELS = {
    "draft-spec": DraftSpec,
    "part-spec": PartSpec,
    "design-proposal": DesignProposal,
    "validation-finding": Finding,
    "inspection-feature": InspectionFeature,
    "build-result": BuildResult,
    "project": Project,
    "template-id": TemplateId,
    "display-units": DisplayUnits,
}


def quote(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def to_ts(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return quote(schema["const"])
    if "enum" in schema:
        return " | ".join(quote(value) for value in schema["enum"])
    for union_key in ("anyOf", "oneOf"):
        if union_key in schema:
            return " | ".join(f"({to_ts(item)})" for item in schema[union_key])
    if "allOf" in schema:
        return " & ".join(f"({to_ts(item)})" for item in schema["allOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join("null" if item == "null" else to_ts({**schema, "type": item}) for item in kind)
    if kind == "array":
        return f"Array<{to_ts(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties") or {}
        if properties:
            fields = [f"  {quote(name)}: {to_ts(value)}" for name, value in properties.items()]
            return "{\n" + ";\n".join(fields) + ";\n}"
        extra = schema.get("additionalProperties")
        return f"Record<string, {to_ts(extra)}>" if isinstance(extra, dict) else "Record<string, unknown>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def main() -> None:
    CONTRACTS.mkdir(parents=True, exist_ok=True)
    definitions: dict[str, dict] = {}
    roots: dict[str, dict] = {}
    for filename, model in MODELS.items():
        schema = model.model_json_schema() if hasattr(model, "model_json_schema") else {"title": model.__name__, "type": "string", "enum": [item.value for item in model]}
        schema_defs = schema.pop("$defs", {})
        definitions.update(schema_defs)
        while any("$defs" in definition for definition in definitions.values()):
            for definition in list(definitions.values()):
                nested = definition.pop("$defs", {})
                definitions.update(nested)
        roots[model.__name__] = schema
        (CONTRACTS / f"{filename}.schema.json").write_text(json.dumps({**schema, "$defs": schema_defs}, indent=2) + "\n")
    lines = ["/* Generated by scripts/generate_contracts.py; do not edit by hand. */", ""]
    for name, schema in {**roots, **definitions}.items():
        lines.append(f"export type {name} = {to_ts(schema)}")
        lines.append("")
    for filename, model in MODELS.items():
        if not hasattr(model, "model_json_schema"):
            continue
        name = re.sub(r"(?:^|-)([a-z])", lambda match: match.group(1).upper(), filename)
        name = name[0].upper() + name[1:]
        lines.extend([f"export type {name}Contract = {model.__name__}", ""])
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
